const SYN = [
  ['西红柿', '番茄'],
  ['马铃薯', '土豆'],
  ['洋芋', '土豆'],
  ['圆白菜', '包菜'],
  ['花椰菜', '花菜'],
  ['蛤蜊', '花蛤'],
  ['云吞', '馄饨'],
  ['四季豆', '豆角'],
  ['北豆腐', '老豆腐'],
  ['南豆腐', '嫩豆腐']
]

// 菜名里常出现的修饰词，匹配前先剥掉
const NOISE = ['家常', '自制', '秘制', '妈妈牌', '我的', '特色', '私房', '拿手', '手工', '一份', '大份', '小份']

const MINOR = ['蒜', '姜', '小葱', '大葱', '香菜', '九层塔', '干辣椒', '小米辣', '紫菜']

// 只做标点清理与同义词归一。
// 注意：「家常」「自制」这类修饰词只能在用户输入上剥，绝不能拿去洗库里的菜名——
// 否则「家常豆腐」会被洗成「豆腐」，任何带豆腐的菜都会错配到它。
function normalize(raw) {
  let s = String(raw || '')
    .replace(/[\s\u3000]+/g, '')
    .replace(/[（）()【】\[\]「」《》·、,，.。!！?？~～\-—_/\\]/g, '')
  SYN.forEach(([from, to]) => {
    s = s.split(from).join(to)
  })
  return s
}

function normalizeInput(raw) {
  let s = normalize(raw)
  NOISE.forEach((w) => {
    s = s.split(w).join('')
  })
  return s
}

function parseTable(raw, withCategory, category) {
  return String(raw || '')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && line.indexOf('|') > 0)
    .map((line) => {
      const parts = line.split('|')
      const name = parts[0].trim()
      const kcal = Math.max(0, Number(parts[1]) || 0)
      const ings = String(parts[2] || '')
        .split(';')
        .map((s) => s.trim())
        .filter(Boolean)
      // 菜谱表是 5 列（含别名），食材表是 4 列，别名的位置不能混用
      const aliases = withCategory
        ? String(parts[3] || '')
            .split(',')
            .map((s) => s.trim())
            .filter(Boolean)
        : []
      const emoji = ((withCategory ? parts[4] : parts[3]) || '').trim() || '🍽️'
      return withCategory
        ? { name, kcal, ings, aliases, emoji, category }
        : { name, kcal, ings, aliases, emoji }
    })
}

const DISHES = Object.keys(DISH_KB_RAW).flatMap((cat) => parseTable(DISH_KB_RAW[cat], true, cat))
const INGREDIENTS = parseTable(ING_KB_RAW, false, '')

// 匹配索引：菜名 + 别名 → 条目
const DISH_INDEX = {}
DISHES.forEach((d) => {
  DISH_INDEX[normalize(d.name)] = d
  d.aliases.forEach((a) => {
    const key = normalize(a)
    if (key && !DISH_INDEX[key]) DISH_INDEX[key] = d
  })
})

const ING_SORTED = [...INGREDIENTS].sort((a, b) => b.name.length - a.name.length)

const KCAL_BASE = 80 // 油 + 调料的粗略基准，拆解估算时补上

function linesOf(ings) {
  return ings.join('\n')
}

function guessCategory(name) {
  if (/粥|饼|包子|馒头|豆浆|燕麦|面|粉|饺子|馄饨|吐司|三明治|油条|汤圆/.test(name)) return '早餐'
  if (/水果|酸奶|坚果|蛋糕|面包|蛋挞|薯条|炸鸡|冰淇淋|雪梨|银耳|豆沙|绿豆/.test(name)) return '加餐'
  return '中晚餐'
}

// 按菜名里的食材词累加
function compose(norm) {
  const hits = []
  const used = []
  const overlap = (start, end) => used.some(([s, e]) => start < e && end > s)
  ING_SORTED.forEach((ing) => {
    let from = 0
    while (true) {
      const at = norm.indexOf(ing.name, from)
      if (at < 0) break
      const end = at + ing.name.length
      if (!overlap(at, end)) {
        hits.push({ ...ing, at })
        used.push([at, end])
        break
      }
      from = at + 1
    }
  })
  if (hits.length === 0) return null

  hits.sort((a, b) => a.at - b.at)
  const main = hits.filter((h) => MINOR.indexOf(h.name) < 0)
  const pool = main.length > 0 ? main : hits
  let kcal = pool.reduce((sum, h) => sum + h.kcal, 0) + KCAL_BASE
  // 汤、羹、粥是分着喝的，一人份摊到的料远少于炒菜，按整份累加会明显偏高
  if (/汤|羹|粥/.test(norm)) kcal *= 0.6
  return {
    kcal: Math.round(kcal / 10) * 10,
    ings: pool.map((h) => h.ings[0]),
    emoji: pool[0].emoji,
    matched: pool.map((h) => h.name),
    category: guessCategory(norm)
  }
}

/**
 * 根据菜名推断热量与食材
 * 返回 null 表示认不出来（不打扰用户）
 * kind: 'dish' 菜谱库命中 / 'compose' 按食材估算
 */
export function inferDish(rawName) {
  const norm = normalizeInput(rawName)
  if (norm.length < 2) return null

  const exact = DISH_INDEX[norm]
  if (exact) {
    return {
      kind: 'dish',
      name: exact.name,
      calories: exact.kcal,
      ingredients: linesOf(exact.ings),
      emoji: exact.emoji,
      category: exact.category,
      confidence: 1,
      note: '菜谱库里有一模一样的'
    }
  }

  // 包含匹配：命中的词要占到菜名的大部分，否则宁可去拆食材。
  // 例如「香菇木耳炒青菜」只命中「炒青菜」（3/7），会丢掉香菇木耳，就该走拆解。
  let best = null
  Object.keys(DISH_INDEX).forEach((key) => {
    if (key.length < 2) return
    let cover = 0
    if (norm.indexOf(key) >= 0) cover = key.length / norm.length
    else if (key.indexOf(norm) >= 0) cover = norm.length / key.length
    if (cover < 0.6) return
    const score = cover * 100 + key.length
    if (!best || score > best.score) best = { score, entry: DISH_INDEX[key] }
  })
  if (best) {
    const d = best.entry
    return {
      kind: 'dish',
      name: d.name,
      calories: d.kcal,
      ingredients: linesOf(d.ings),
      emoji: d.emoji,
      category: d.category,
      confidence: 0.75,
      note: '和「' + d.name + '」最接近'
    }
  }

  // 最后退回按食材拆解
  const c = compose(norm)
  if (!c) return null
  return {
    kind: 'compose',
    name: '',
    calories: c.kcal,
    ingredients: linesOf(c.ings),
    emoji: c.emoji,
    category: c.category,
    confidence: c.matched.length >= 2 ? 0.55 : 0.4,
    matched: c.matched,
    note: '按名称里的食材估算'
  }
}

